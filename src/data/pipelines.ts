import type { Pipeline, PipelineId, Stage } from '../types/pipeline'

/* Ported verbatim from legacy/index.html lines 693-765. */

function s(
  id: string,
  title: string,
  icon: string,
  summary: string,
  checklist: string[],
  tools: string[],
  deliverable: string,
  time: string,
  refine: string,
): Stage {
  return { id, title, icon, summary, checklist, tools, deliverable, time, refine }
}

